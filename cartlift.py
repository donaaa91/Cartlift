def srm_check(df):
    results = {}
    overall = df["arm"].value_counts()
    chi2, p = stats.chisquare(overall.values)
    results["overall"] = {"counts": overall.to_dict(), "p_value": p, "srm_flag": p < 0.01}
    for device, sub in df.groupby("device"):
        counts = sub["arm"].value_counts()
        chi2, p = stats.chisquare(counts.values)
        results[f"device={device}"] = {"counts": counts.to_dict(), "p_value": p, "srm_flag": p < 0.01}
    return results

srm_check(df)

