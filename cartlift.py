import os

def simulate():
    rows = []
    session_id = 1
    for day in range(N_DAYS):
        date = START_DATE + pd.Timedelta(days=day)
        n_sessions = RNG.poisson(DAILY_SESSIONS_MEAN)
        p_mobile_today = P_MOBILE
        p_new_today = P_NEW_USER
        if BUG_START_DAY <= day <= BUG_END_DAY:
            p_mobile_today = min(0.75, P_MOBILE + 0.12)
            p_new_today = min(0.60, P_NEW_USER + 0.10)

        for _ in range(n_sessions):
            device = "mobile" if RNG.random() < p_mobile_today else "desktop"
            user_type = "new" if RNG.random() < p_new_today else "returning"
            arm = assign_arm(day, device)

            base = BASE_CVR[(device, user_type)]
            lift = TRUE_LIFT[(device, user_type)] if arm == "treatment" else 0.0
            p_convert = np.clip(base + lift, 0.001, 0.999)
            converted = RNG.random() < p_convert

            base_load = BASE_LOAD_MS[device]
            mult = (1 + TREATMENT_LOAD_REGRESSION) if arm == "treatment" else 1.0
            page_load_ms = RNG.lognormal(mean=np.log(base_load * mult), sigma=0.22)

            rows.append({"session_id": session_id, "date": date, "day_index": day,
                          "device": device, "user_type": user_type, "arm": arm,
                          "converted": int(converted), "page_load_ms": round(page_load_ms, 1)})
            session_id += 1
    return pd.DataFrame(rows)

df = simulate()

