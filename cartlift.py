import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.stats.power import NormalIndPower
from statsmodels.stats.proportion import proportions_ztest
import matplotlib.pyplot as plt

RNG = np.random.default_rng(42)
# %matplotlib inline

N_DAYS = 21
START_DATE = pd.Timestamp("2026-06-01")
DAILY_SESSIONS_MEAN = 2000

P_MOBILE = 0.55
P_NEW_USER = 0.40

BUG_START_DAY = 1
BUG_END_DAY = 5
BUG_MOBILE_TREATMENT_BOOST = 0.30

BASE_CVR = {
    ("mobile", "new"): 0.062, ("mobile", "returning"): 0.081,
    ("desktop", "new"): 0.071, ("desktop", "returning"): 0.093,
}
TRUE_LIFT = {
    ("mobile", "new"): 0.058, ("mobile", "returning"): 0.048,
    ("desktop", "new"): 0.004, ("desktop", "returning"): -0.002,
}
BASE_LOAD_MS = {"mobile": 1850, "desktop": 1400}
TREATMENT_LOAD_REGRESSION = 0.085

def assign_arm(day, device):
    p_treat = 0.5
    if device == "mobile" and BUG_START_DAY <= day <= BUG_END_DAY:
        p_treat = min(0.95, 0.5 + BUG_MOBILE_TREATMENT_BOOST)
    return "treatment" if RNG.random() < p_treat else "control"

