def power_analysis(df, mde=0.015, alpha=0.05):
    analysis = NormalIndPower()
    rows = []
    for (device, user_type), sub in df.groupby(["device", "user_type"]):
        ctrl = sub[sub.arm == "control"]
        n_c, n_t = len(ctrl), len(sub[sub.arm == "treatment"])
        n_per_arm = min(n_c, n_t)
        p_base = ctrl["converted"].mean()
        h = 2*np.arcsin(np.sqrt(p_base+mde)) - 2*np.arcsin(np.sqrt(p_base))
        power = analysis.solve_power(effect_size=h, nobs1=n_per_arm, alpha=alpha, ratio=1.0, alternative="two-sided")
        rows.append({"device": device, "user_type": user_type, "n_per_arm": n_per_arm,
                      "achieved_power": power, "adequately_powered": power >= 0.80})
    return pd.DataFrame(rows)

